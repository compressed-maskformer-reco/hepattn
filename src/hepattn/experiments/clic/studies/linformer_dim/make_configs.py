"""Generate the decoder-only Linformer k scan from the linformer_size small reference.

Shrinking linformer_k in the encoder degrades the encoder loss terms, so this scan halves it only in the decoder,
where one value is shared by the query<-hits and hits<-query cross-attentions and the query self-attention.
The encoder stays at k 64. Every arm starts from linformer_size/configs/small_ref_linformer.yaml with:
  peak LR 8e-5 -> 3.2e-4, 200 epochs (unchanged), global batch 2048 (1 device x 2048, as submit_training_b200.sh runs it),
  decoder linformer_k 64 -> {64, 32, 16, 8, 4}. deck64 is the reference at the new LR.
A second set repeats the scan with peak LR 6.2e-4, weight_decay 0.1 and 400 epochs, under the name tag
lr6p2e-4_wd0p1_ep400 so its runs never share a config or a log folder with the first set's.
Usage: python make_configs.py <../linformer_size/configs/small_ref_linformer.yaml> <outdir>
"""

import sys
from pathlib import Path

ref, outdir = Path(sys.argv[1]).read_text(), Path(sys.argv[2])

KS = [64, 32, 16, 8, 4]
# name tag -> (peak LR, weight decay, epochs); the untagged set is the first scan, written exactly as before.
SETS = {"": ("3.2e-4", "1e-4", 200), "lr6p2e-4_wd0p1_ep400": ("6.2e-4", "0.1", 400)}
DEC_K = "            linformer_seq_len: 160\n            linformer_k: {k}\n"  # the encoder's seq_len is 168


def sub1(s, old, new):
    assert s.count(old) == 1, (old, s.count(old))
    return s.replace(old, new)


def base(s, lr, wd, epochs):
    s = sub1(s, "# Generated by make_configs.py; do not edit.\n", "")
    s = sub1(s, "    max: 8e-5\n", f"    max: {lr}\n")
    s = sub1(s, "    weight_decay: 1e-4\n", f"    weight_decay: {wd}\n")
    s = sub1(s, "  max_epochs: 200\n", f"  max_epochs: {epochs}\n")
    s = sub1(s, "  devices: 2\n", "  devices: 1\n")
    return sub1(s, "  batch_size: 512\n", "  batch_size: 2048\n")


def deck(s, k):
    return sub1(s, DEC_K.format(k=64), DEC_K.format(k=k))


outdir.mkdir(parents=True, exist_ok=True)
for tag, (lr, wd, epochs) in SETS.items():
    s = base(ref, lr, wd, epochs)
    for k in KS:
        name = f"small_linformer_{tag + '_' if tag else ''}deck{k}"
        text = sub1(deck(s, k), "name: clic_small_ref_linformer\n", f"name: clic_{name}\n")
        header = "# Generated by studies/linformer_dim/make_configs.py from linformer_size/configs/small_ref_linformer.yaml; do not edit.\n"
        (outdir / f"{name}.yaml").write_text(header + text)
        print("wrote", name)
